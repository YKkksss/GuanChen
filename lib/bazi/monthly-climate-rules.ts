const seasonLabels=['春','夏','秋','冬'],monthNames=['正月','二月','三月','四月','五月','六月','七月','八月','九月','十月','十一月','十二月'];
export const BAZI_MONTHLY_CLIMATE_REFERENCES: Record<string,MonthlyClimateReference> = Object.fromEntries(Object.entries(TABLE).flatMap(([stem,rows]) => {
  if (rows.length !== 12) throw new Error(`${stem}的月令参考必须包含十二条`);
  return rows.map(([core,rationale,extra=[],specifiedBasis,periodNote],i): [string,MonthlyClimateReference] => {
    const basis=specifiedBasis ?? 'month_paragraph';
    const section=`三${seasonLabels[Math.floor(i/3)]}${stem}${STEM_ELEMENT[stem]}`;
    const conditional=extra.map(([s,when,detail])=>({stem:s,when,detail}));
    return [`${stem}:${CLIMATE_BRANCH_ORDER[i]}`,{elements:[...new Set([...core].map(s=>STEM_ELEMENT[s]))],stems:[...new Set([...core,...conditional.map(c=>c.stem)])],coreStems:[...core],rationale,section:`${section} · ${basis==='shared_paragraph'?'合论（映射'+monthNames[i]+'）':monthNames[i]}`,sourceUrl:`${MONTHLY_CLIMATE_SOURCE}#${section}`,basis,conditional,periodNote:periodNote??null}];
  });
}));
